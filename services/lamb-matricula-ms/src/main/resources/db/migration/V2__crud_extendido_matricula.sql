CREATE TABLE IF NOT EXISTS periodos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    fecha_limite_matricula DATE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_periodos_academicos_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS tipos_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(150) NOT NULL,
    dias_plazo_extra INTEGER NOT NULL DEFAULT 0,
    recargo NUMERIC(5,2) NOT NULL DEFAULT 0,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_tipos_matricula_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS cronogramas_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_periodo_academico BIGINT NOT NULL REFERENCES periodos_academicos(id),
    id_tipo_matricula BIGINT NOT NULL REFERENCES tipos_matricula(id),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS secciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL,
    id_periodo_academico BIGINT NOT NULL REFERENCES periodos_academicos(id),
    cupo_maximo INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS reservas_vacante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_seccion BIGINT NOT NULL REFERENCES secciones(id),
    fecha_reserva TIMESTAMP NOT NULL,
    fecha_expiracion TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS motivos_anulacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(150) NOT NULL,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_motivos_anulacion_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS historial_estado_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_matricula BIGINT NOT NULL REFERENCES matriculas(id),
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS limites_creditos_ciclo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ciclo INTEGER NOT NULL,
    creditos_maximos INTEGER NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_limites_creditos_ciclo UNIQUE (ciclo)
);

CREATE TABLE IF NOT EXISTS solicitudes_excepcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_seccion BIGINT REFERENCES secciones(id),
    id_matricula BIGINT REFERENCES matriculas(id),
    motivo VARCHAR(250) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_solicitud TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

