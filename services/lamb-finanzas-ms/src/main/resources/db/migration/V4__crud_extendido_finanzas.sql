ALTER TABLE pagos ADD COLUMN IF NOT EXISTS id_motivo_pago BIGINT;

CREATE TABLE IF NOT EXISTS metodos_pago_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    comision NUMERIC(10,2) NOT NULL,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_metodos_pago_config_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS configuraciones_mora (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    dias_gracia INTEGER NOT NULL,
    porcentaje_mora_diario NUMERIC(10,2) NOT NULL,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_configuraciones_mora_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS motivos_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    tipo VARCHAR(20) NOT NULL,
    codigo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(150) NOT NULL,
    vigente BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_motivos_pago_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS cuotas_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pago BIGINT NOT NULL,
    numero_cuota INTEGER NOT NULL,
    monto_cuota NUMERIC(10,2) NOT NULL,
    fecha_vencimiento TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_pago TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_cuotas_pago_pago FOREIGN KEY (id_pago) REFERENCES pagos (id)
);

CREATE TABLE IF NOT EXISTS planes_refinanciamiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_pago_original BIGINT NOT NULL,
    numero_cuotas INTEGER NOT NULL,
    monto_total NUMERIC(10,2) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS descuentos_aplicados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_pago BIGINT,
    tipo VARCHAR(20) NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    descripcion VARCHAR(150) NOT NULL,
    fecha_aplicacion TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS documentos_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pago BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    numero VARCHAR(50) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_emision TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_documentos_pago_numero UNIQUE (numero),
    CONSTRAINT fk_documentos_pago_pago FOREIGN KEY (id_pago) REFERENCES pagos (id)
);

CREATE TABLE IF NOT EXISTS transacciones_pasarela (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pago BIGINT NOT NULL,
    referencia VARCHAR(100) NOT NULL,
    monto NUMERIC(10,2) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_transacciones_pasarela_pago FOREIGN KEY (id_pago) REFERENCES pagos (id)
);

CREATE TABLE IF NOT EXISTS historial_estado_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pago BIGINT NOT NULL,
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL,
    fecha TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_historial_estado_pago_pago FOREIGN KEY (id_pago) REFERENCES pagos (id)
);
